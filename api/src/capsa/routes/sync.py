"""Learning events (SPEC 6): idempotent upload, incremental download by server_seq."""

from __future__ import annotations

import uuid
from typing import Annotated, Literal

from fastapi import APIRouter, Query
from pydantic import AwareDatetime, BaseModel, Field, field_validator
from sqlalchemy import insert, select

from capsa.access import readable_profiles
from capsa.clock import from_datetime, to_datetime
from capsa.db import events
from capsa.deps import Conn, CurrentUser, State

router = APIRouter(tags=["sync"])

MAX_BATCH = 500
Direction = Literal["src_to_tr", "tr_to_src"]
Mode = Literal["flashcard", "typed", "choice", "parent"]


class Event(BaseModel):
    """One answer. Immutable; the learning state is computed from all events."""

    id: str = Field(description="UUIDv7, generated by the client")
    device_id: str = Field(min_length=1, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")
    profile_id: str = Field(min_length=1, max_length=128)
    entry_id: str = Field(min_length=1, max_length=128)
    direction: Direction
    mode: Mode
    correct: bool
    response_ms: int | None = Field(default=None, ge=0, le=3_600_000)
    ts: AwareDatetime = Field(description="client time of the answer")

    @field_validator("id")
    @classmethod
    def _uuid7(cls, value: str) -> str:
        try:
            parsed = uuid.UUID(value)
        except ValueError:
            raise ValueError("not a UUID") from None
        if parsed.version != 7:
            raise ValueError("must be a UUIDv7")
        return str(parsed)


class StoredEvent(Event):
    server_seq: int
    received_at: AwareDatetime


class EventBatch(BaseModel):
    events: list[Event] = Field(max_length=MAX_BATCH)


class Rejected(BaseModel):
    id: str
    reason: Literal["unknown_profile", "unknown_entry", "id_conflict"]


class UploadResult(BaseModel):
    accepted: int
    duplicates: int
    rejected: list[Rejected]


class EventPage(BaseModel):
    events: list[StoredEvent]
    next_since: int = Field(description="pass as `since` for the next request")
    more: bool


@router.post("/sync/events")
def upload_events(batch: EventBatch, user: CurrentUser, conn: Conn, state: State) -> UploadResult:
    now = state.clock()
    profiles = {p.id: p for p in readable_profiles(conn, user, state.profiles)}
    ids = [e.id for e in batch.events]
    found = conn.execute(select(events.c.id, events.c.user_id).where(events.c.id.in_(ids)))
    owners = {row.id: row.user_id for row in found}

    rows, rejected, duplicates, seen = [], [], 0, set()
    for e in batch.events:
        if e.id in seen or owners.get(e.id) == user.id:
            duplicates += 1
            continue
        if e.id in owners:
            rejected.append(Rejected(id=e.id, reason="id_conflict"))
            continue
        profile = profiles.get(e.profile_id)
        if profile is None:
            rejected.append(Rejected(id=e.id, reason="unknown_profile"))
            continue
        if e.entry_id not in profile.entry_ids:
            rejected.append(Rejected(id=e.id, reason="unknown_entry"))
            continue
        seen.add(e.id)
        rows.append(
            {
                **e.model_dump(exclude={"ts"}),
                "user_id": user.id,
                "ts": from_datetime(e.ts),
                "received_at": now,
            }
        )
    if rows:
        conn.execute(insert(events), rows)
    return UploadResult(accepted=len(rows), duplicates=duplicates, rejected=rejected)


@router.get("/sync/events")
def download_events(
    user: CurrentUser,
    conn: Conn,
    since: Annotated[int, Query(ge=0, description="last server_seq already known")] = 0,
    limit: Annotated[int, Query(ge=1, le=MAX_BATCH)] = MAX_BATCH,
) -> EventPage:
    rows = conn.execute(
        select(events)
        .where(events.c.user_id == user.id, events.c.server_seq > since)
        .order_by(events.c.server_seq)
        .limit(limit + 1)
    ).all()
    more = len(rows) > limit
    rows = rows[:limit]
    page = [
        StoredEvent(
            id=r.id,
            device_id=r.device_id,
            profile_id=r.profile_id,
            entry_id=r.entry_id,
            direction=r.direction,
            mode=r.mode,
            correct=r.correct,
            response_ms=r.response_ms,
            ts=to_datetime(r.ts),
            server_seq=r.server_seq,
            received_at=to_datetime(r.received_at),
        )
        for r in rows
    ]
    return EventPage(events=page, next_since=rows[-1].server_seq if rows else since, more=more)
